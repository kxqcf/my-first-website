/* ============================================================
   counter.js —— 功能模块：按钮点击计数
   ------------------------------------------------------------
   一个文件只干一件事。
   注意这里只"定义"函数，不主动执行 —— 真正的启动交给 main.js。
   这样职责很清楚：想知道页面启动时跑了什么，只看 main.js 就行。
   ============================================================ */

function initCounter() {
  // 1. 先找到要操作的两个元素。
  //    id 要和 index.html 里写的完全一致，大小写敏感。
  const btn = document.getElementById("hiBtn");
  const text = document.getElementById("hiText");

  // 2. 找不到元素就直接退出。
  //    以后你把按钮从 HTML 里删掉时，这里不会报错崩掉整个页面。
  //    这种"先检查再使用"的习惯，能省掉大量莫名其妙的红字报错。
  if (!btn || !text) {
    return;
  }

  // 3. 用 count 记录点击次数。
  //    它写在函数内部，外面访问不到，不会污染全局。
  let count = 0;

  // 4. 绑定点击事件。
  //    这里的 function 叫"回调函数"：
  //    现在不执行，等用户点了按钮，浏览器才回头调用它。
  btn.addEventListener("click", function () {
    count = count + 1;

    // textContent 是元素里的纯文字。
    // 用它而不是 innerHTML，因为插入纯文字更安全、也更快。
    text.textContent = "你已经点了 " + count + " 次，恭喜你，你刚刚写下了第一行会跑的代码。";
  });
}
